# The report puts some titles mid-name ("Ivan dr. med. Prgomet"), writes
# nicknames as a dash or bracket suffix ("Ivica Ančić - Duje", "Mijo Družić
# (Brozek)"), and gives one member his noble title. None of that is part of the
# name a person is matched on across years.
_MID_TITLE = re.compile(r'\b(dr\.\s*(med|stom)\.|grof)\s+', re.I)
_NICKNAME = re.compile(r'\s+-\s+\S+|\s*\([^)]*\)')

# Spellings that would otherwise fork a person already in the database, each
# with its evidence. Hyphen-only differences (Dabčević-Kučar) are left to
# `merge_person_aliases`, which folds that class automatically.
ALIASES = {
    # The 1992 decision prints "Biljo-Friganović"; she is the SDP member who sat
    # again from 1995 as Snježana Biga Friganović. "Biljo" is a typo.
    'SNJEŽANA BILJO-FRIGANOVIĆ': 'SNJEŽANA BIGA FRIGANOVIĆ',
    # "Bolta" is the short form of Baltazar: HSLS, Čakovec in 1992, HSLS list
    # member in 1995.
    'BOLTA JALŠOVEC': 'BALTAZAR JALŠOVEC',
}


def person_name(raw):
    name = _NICKNAME.sub('', _MID_TITLE.sub('', raw))
    name = clean_candidate_name(name).upper()
    return ALIASES.get(name, name)
